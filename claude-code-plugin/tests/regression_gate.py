"""Regression gate for the ChaosMonkey Claude Code plugin work.

Records (or compares against) a baseline of the guarantees the plugin must not weaken:
  * GET /api/health  (privacy attestation, mode, KB size)
  * GET /api/determinism-check, run twice (hash must be identical across runs)
  * a normalized hash of the full report for the vulnerable demo fixture (flask_store)

Runs in-process against the current backend code via FastAPI's TestClient, with LLM_MOCK=1
so the result is reproducible offline. Usage (from the repo root):

    backend/.venv/Scripts/python claude-code-plugin/tests/regression_gate.py --save baseline.json
    backend/.venv/Scripts/python claude-code-plugin/tests/regression_gate.py --compare baseline.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

os.environ.setdefault("LLM_MOCK", "1")
os.environ.setdefault("SEED", "42")

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "backend"))

from fastapi.testclient import TestClient  # noqa: E402

from app.main import app  # noqa: E402
from app.pipeline.ingest import ingest_path  # noqa: E402
from app.pipeline.orchestrator import ScanOptions, run_scan  # noqa: E402

FIXTURE = REPO / "demo" / "apps" / "flask_store"


def demo_report_hash() -> tuple[str, int]:
    ing = ingest_path(str(FIXTURE))
    # Only the source files: the runtime canary file is generated by the demo and may come and go.
    ing.files = [f for f in ing.files if f.path.endswith(".py")]
    report = run_scan(ing, ScanOptions(name="regression-gate"), "gate").model_dump()
    report.pop("durationMs", None)
    report["id"] = ""
    blob = json.dumps(report, sort_keys=True)
    return hashlib.sha256(blob.encode()).hexdigest()[:16], len(report["findings"])


def collect() -> dict:
    with TestClient(app) as client:
        health = client.get("/api/health").json()
        det1 = client.get("/api/determinism-check").json()
        det2 = client.get("/api/determinism-check").json()
    demo_hash, demo_findings = demo_report_hash()
    return {
        "health": health,
        "determinism": [
            {k: det1[k] for k in ("identical", "hash_run1", "hash_run2", "finding_ids_run1")},
            {k: det2[k] for k in ("identical", "hash_run1", "hash_run2", "finding_ids_run1")},
        ],
        "demo_report_hash": demo_hash,
        "demo_findings": demo_findings,
    }


def check(snapshot: dict) -> list[str]:
    problems = []
    h = snapshot["health"]
    if h.get("data_leaves_machine") is not False:
        problems.append("health: data_leaves_machine is not false")
    if h.get("privacy_ok") is not True:
        problems.append("health: privacy_ok is not true")
    for i, d in enumerate(snapshot["determinism"], 1):
        if d["identical"] is not True:
            problems.append(f"determinism run {i}: identical is not true")
    if snapshot["determinism"][0] != snapshot["determinism"][1]:
        problems.append("determinism: the two determinism-check calls differ")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--save")
    ap.add_argument("--compare")
    args = ap.parse_args()
    snap = collect()
    problems = check(snap)
    if args.compare:
        base = json.loads(Path(args.compare).read_text(encoding="utf-8"))
        for key in ("health", "determinism", "demo_report_hash", "demo_findings"):
            if base[key] != snap[key]:
                problems.append(f"{key} differs from baseline:\n  baseline={base[key]}\n  now     ={snap[key]}")
    if args.save:
        Path(args.save).write_text(json.dumps(snap, indent=2, sort_keys=True), encoding="utf-8")
    print(json.dumps({"determinism_hash": snap["determinism"][0]["hash_run1"],
                      "demo_report_hash": snap["demo_report_hash"],
                      "demo_findings": snap["demo_findings"],
                      "health": {k: snap["health"][k] for k in ("status", "mode", "data_leaves_machine", "privacy_ok", "kb_size")}},
                     indent=2))
    if problems:
        print("REGRESSION GATE FAILED:\n- " + "\n- ".join(problems))
        return 1
    print("REGRESSION GATE OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
