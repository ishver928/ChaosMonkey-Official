import type { Dismissal, Finding, ScanReport } from './types'
import { RULE_BY_ID } from './rules'
import { adviceFor } from './knowledge'
import { CATEGORIES, CATEGORY_LABEL, SEVERITIES, SEVERITY_LABEL, chaosScore, countBy, scoreLabel } from './severity'
import { scrub } from './redaction'

/* Exports are built only from masked findings, then scrubbed again. File contents are never included. */

interface ExportInput { report: ScanReport; dismissed: Record<string, Dismissal> }

function split({ report, dismissed }: ExportInput) {
  const active = report.findings.filter((f) => !dismissed[f.fingerprint])
  const muted = report.findings.filter((f) => dismissed[f.fingerprint])
  return { active, muted }
}

const stamp = (t: number) => new Date(t).toLocaleString('en-US', { dateStyle: 'medium', timeStyle: 'short' })

export function toJSON(input: ExportInput): string {
  const { report, dismissed } = input
  const { active } = split(input)
  const payload = {
    tool: 'ChaosMonkey',
    version: 1,
    project: report.name,
    scannedAt: new Date(report.createdAt).toISOString(),
    chaosScore: chaosScore(active),
    files: report.files.map((f) => ({ path: f.path, language: f.language, lines: f.lines })),
    findings: report.findings.map((f) => ({
      rule: f.ruleId, title: RULE_BY_ID[f.ruleId]?.title, category: f.category, severity: f.severity,
      file: f.file, line: f.line, column: f.column, endLine: f.endLine, endColumn: f.endColumn,
      maskedValue: f.maskedValue || undefined, snippet: f.snippet, confidence: f.confidence, note: f.note,
      fingerprint: f.fingerprint, status: dismissed[f.fingerprint]?.reason ?? 'open',
    })),
  }
  return scrub(JSON.stringify(payload, null, 2))
}

export function toMarkdown(input: ExportInput): string {
  const { report } = input
  const { active, muted } = split(input)
  const score = chaosScore(active)
  const sev = countBy(active, (f) => f.severity, SEVERITIES)
  const out: string[] = [
    `# ChaosMonkey report: ${report.name}`,
    '',
    `Scanned ${stamp(report.createdAt)} · ${report.files.length} files · ${report.rulesRun} rules · ran locally, nothing uploaded.`,
    '',
    `**Chaos Score: ${score}/100 (${scoreLabel(score).label})**`,
    '',
    '| Severity | Open findings |', '| --- | --- |',
    ...SEVERITIES.map((s) => `| ${SEVERITY_LABEL[s]} | ${sev[s]} |`),
    '',
  ]
  for (const c of CATEGORIES) {
    const list = active.filter((f) => f.category === c)
    if (!list.length) continue
    out.push(`## ${CATEGORY_LABEL[c]} (${list.length})`, '')
    for (const f of list) {
      const a = adviceFor(f)
      out.push(
        `### [${SEVERITY_LABEL[f.severity]}] ${RULE_BY_ID[f.ruleId]?.title ?? f.ruleId} (${f.ruleId})`,
        '',
        `\`${f.file}:${f.line}:${f.column}\` · confidence ${Math.round(f.confidence * 100)}%${f.note ? ` · ${f.note}` : ''}`,
        '', '```', f.snippet, '```', '',
        `**Why it's dangerous:** ${a.why}`, '',
        ...a.steps.map((s) => `- ${s}`), '',
        '**Suggested fix:**', '', '```' + a.fix.language, a.fix.after, '```', '',
      )
    }
  }
  if (muted.length) {
    out.push('## Dismissed', '', ...muted.map((f) => `- ${f.ruleId} \`${f.file}:${f.line}\` (${input.dismissed[f.fingerprint]?.reason.replace('-', ' ')})`), '')
  }
  out.push('---', 'Generated by ChaosMonkey. All secret and personal values are masked.')
  return scrub(out.join('\n'))
}

const h = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

export function toHTML(input: ExportInput): string {
  const { report } = input
  const { active, muted } = split(input)
  const score = chaosScore(active)
  const sev = countBy(active, (f) => f.severity, SEVERITIES)
  const colors: Record<string, string> = { critical: '#9B2F22', high: '#A8510F', medium: '#7A5A00', low: '#315A80' }
  const row = (f: Finding) => {
    const a = adviceFor(f)
    return `<article><header><span class="sev" style="border-color:${colors[f.severity]};color:${colors[f.severity]}">${SEVERITY_LABEL[f.severity]}</span>
<h3>${h(RULE_BY_ID[f.ruleId]?.title ?? f.ruleId)} <small>${f.ruleId}</small></h3></header>
<p class="loc">${h(f.file)}:${f.line}:${f.column} · confidence ${Math.round(f.confidence * 100)}%${f.note ? ` · ${h(f.note)}` : ''}</p>
<pre>${h(f.snippet)}</pre><p>${h(a.why)}</p><ul>${a.steps.map((s) => `<li>${h(s)}</li>`).join('')}</ul>
<p class="lbl">Suggested fix</p><pre class="fix">${h(a.fix.after)}</pre></article>`
  }
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'">
<title>ChaosMonkey report: ${h(report.name)}</title><style>
body{margin:0;background:#FFF9E9;color:#594237;font:15px/1.55 system-ui,-apple-system,"Segoe UI",sans-serif}
main{max-width:900px;margin:0 auto;padding:48px 24px}h1,h2,h3{color:#38291F;line-height:1.1}h1{font-size:40px;margin:0 0 6px}
.meta{font:12px ui-monospace,Consolas,monospace}.score{display:flex;gap:24px;align-items:center;border:2px solid #594237;background:#FFFEFA;box-shadow:4px 4px 0 #594237;padding:20px;margin:28px 0}
.score b{font-size:56px;color:#38291F}.counts{display:flex;gap:16px;flex-wrap:wrap}.counts span{border:1px solid #594237;padding:2px 8px;font:12px ui-monospace,monospace}
article{border:1px solid #594237;background:#FFFEFA;padding:16px 18px;margin:14px 0}article header{display:flex;gap:10px;align-items:center}article h3{margin:0;font-size:18px}
small{font:11px ui-monospace,monospace;color:#7a6658}.sev{border:1.5px solid;padding:1px 7px;font:700 11px ui-monospace,monospace;text-transform:uppercase}
.loc{font:12px ui-monospace,monospace;margin:6px 0}pre{background:#FFFDF7;border:1px solid rgba(89,66,55,.3);padding:10px;overflow:auto;font:12.5px/1.5 ui-monospace,Consolas,monospace;white-space:pre-wrap}
pre.fix{background:#F4FAF1}.lbl{font-weight:800;font-size:12px;text-transform:uppercase;letter-spacing:.1em;margin-bottom:4px}footer{margin-top:40px;font-size:12px}
</style></head><body><main>
<p class="meta">CHAOSMONKEY · LOCAL SCAN REPORT</p><h1>${h(report.name)}</h1>
<p class="meta">${stamp(report.createdAt)} · ${report.files.length} files · ${report.rulesRun} rules · nothing left this machine</p>
<section class="score"><b>${score}</b><div><strong>${scoreLabel(score).label}</strong><p>${h(scoreLabel(score).blurb)}</p>
<div class="counts">${SEVERITIES.map((s) => `<span>${SEVERITY_LABEL[s]}: ${sev[s]}</span>`).join('')}</div></div></section>
${CATEGORIES.map((c) => { const list = active.filter((f) => f.category === c); return list.length ? `<h2>${CATEGORY_LABEL[c]} (${list.length})</h2>${list.map(row).join('')}` : '' }).join('')}
${muted.length ? `<h2>Dismissed (${muted.length})</h2><ul>${muted.map((f) => `<li>${f.ruleId} ${h(f.file)}:${f.line}</li>`).join('')}</ul>` : ''}
<footer>All secret and personal values in this file are masked. Generated offline by ChaosMonkey.</footer></main></body></html>`
  return scrub(html)
}

export function download(filename: string, text: string, mime: string): void {
  const url = URL.createObjectURL(new Blob([text], { type: mime }))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export function exportReport(kind: 'md' | 'json' | 'html', input: ExportInput): void {
  const base = `chaosmonkey-${input.report.name.replace(/[^\w.-]+/g, '-')}-${new Date(input.report.createdAt).toISOString().slice(0, 10)}`
  if (kind === 'md') download(`${base}.md`, toMarkdown(input), 'text/markdown')
  if (kind === 'json') download(`${base}.json`, toJSON(input), 'application/json')
  if (kind === 'html') download(`${base}.html`, toHTML(input), 'text/html')
}
